function trackEvent(eventName: string) {
  if (typeof window === "undefined") return;

  window.dataLayer?.push({
    event: eventName,
    event_category: "links",
    event_label: eventName,
  });

  window.gtag?.("event", eventName, {
    event_category: "links",
    event_label: eventName,
  });
}

